-- ---------- 单表：客户 ----------

CREATE TABLE SAMPLE_CUSTOMER (
    CUSTOMER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CUSTOMER_NAME VARCHAR(64) NOT NULL,
    PHONE VARCHAR(20),
    EMAIL VARCHAR(64),
    STATUS CHAR(1) DEFAULT '0',
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    CONSTRAINT PK_SAMPLE_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);
COMMENT ON COLUMN SAMPLE_CUSTOMER.STATUS IS '状态（0正常 1停用）';

-- ---------- 树表：商品分类 ----------

CREATE TABLE SAMPLE_CATEGORY (
    CATEGORY_ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CATEGORY_NAME VARCHAR(64) NOT NULL,
    PARENT_ID BIGINT DEFAULT 0,
    ANCESTORS VARCHAR(500) DEFAULT '',
    ORDER_NUM INT DEFAULT 0,
    STATUS CHAR(1) DEFAULT '0',
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    CONSTRAINT PK_SAMPLE_CATEGORY PRIMARY KEY (CATEGORY_ID)
);

-- ---------- 主表：订单 ----------

CREATE TABLE SAMPLE_ORDER (
    ORDER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ORDER_NO VARCHAR(32) NOT NULL,
    CUSTOMER_ID BIGINT,
    TOTAL_AMOUNT DECIMAL(12,2) DEFAULT 0,
    STATUS CHAR(1) DEFAULT '0',
    AUDIT_REMARK VARCHAR(500),
    REMARK VARCHAR(500),
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    CONSTRAINT PK_SAMPLE_ORDER PRIMARY KEY (ORDER_ID)
);
COMMENT ON COLUMN SAMPLE_ORDER.STATUS IS '状态（0待提交 1审批中 2已通过 3已驳回）';

-- ---------- 子表：订单明细 ----------

CREATE TABLE SAMPLE_ORDER_ITEM (
    ITEM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ORDER_ID BIGINT NOT NULL,
    PRODUCT_NAME VARCHAR(128) NOT NULL,
    QUANTITY INT DEFAULT 1,
    PRICE DECIMAL(12,2) DEFAULT 0,
    CONSTRAINT PK_SAMPLE_ORDER_ITEM PRIMARY KEY (ITEM_ID)
);

-- ---------- 单表：库存 ----------

CREATE TABLE SAMPLE_STOCK (
    STOCK_ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    PRODUCT_NAME VARCHAR(128) NOT NULL,
    CATEGORY_ID BIGINT,
    QUANTITY INT DEFAULT 0,
    WAREHOUSE VARCHAR(64) DEFAULT '',
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    CONSTRAINT PK_SAMPLE_STOCK PRIMARY KEY (STOCK_ID)
);

