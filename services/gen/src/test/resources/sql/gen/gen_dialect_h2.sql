CREATE TABLE gen_table (
    table_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name        VARCHAR(200) DEFAULT '',
    table_comment     VARCHAR(500) DEFAULT '',
    sub_table_name    VARCHAR(64),
    sub_table_fk_name VARCHAR(64),
    class_name        VARCHAR(100) DEFAULT '',
    tpl_category      VARCHAR(200) DEFAULT 'crud',
    tpl_web_type      VARCHAR(30)  DEFAULT '',
    package_name      VARCHAR(100),
    module_name       VARCHAR(30),
    business_name     VARCHAR(30),
    function_name     VARCHAR(50),
    function_author   VARCHAR(50),
    form_col_num      NUMBER(1)    DEFAULT 1,
    gen_type          CHAR(1)      DEFAULT '0',
    gen_path          VARCHAR(200) DEFAULT '/',
    options           VARCHAR(1000),
    create_by         VARCHAR(64)  DEFAULT '',
    create_time       TIMESTAMP,
    update_by         VARCHAR(64)  DEFAULT '',
    update_time       TIMESTAMP,
    remark            VARCHAR(500),
    version           BIGINT DEFAULT 0 NOT NULL
);

CREATE TABLE gen_table_column (
    column_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id       BIGINT,
    column_name    VARCHAR(200),
    column_comment VARCHAR(500),
    column_type    VARCHAR(100),
    java_type      VARCHAR(500),
    java_field     VARCHAR(200),
    is_pk          CHAR(1),
    is_increment   CHAR(1),
    is_required    CHAR(1),
    is_insert      CHAR(1),
    is_edit        CHAR(1),
    is_list        CHAR(1),
    is_query       CHAR(1),
    query_type     VARCHAR(200) DEFAULT 'EQ',
    html_type      VARCHAR(200),
    dict_type      VARCHAR(200) DEFAULT '',
    sort           NUMBER(10),
    create_by      VARCHAR(64)  DEFAULT '',
    create_time    TIMESTAMP,
    update_by      VARCHAR(64)  DEFAULT '',
    update_time    TIMESTAMP,
    version        BIGINT DEFAULT 0 NOT NULL
);
