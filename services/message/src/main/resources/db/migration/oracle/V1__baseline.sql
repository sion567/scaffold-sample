    SEND_STATUS     VARCHAR2(16)   DEFAULT 'PENDING' NOT NULL,
    FAIL_REASON     VARCHAR2(512),
    RETRY_COUNT     NUMBER(4)      DEFAULT 0,
    SEND_TIME       TIMESTAMP(0),
    BIZ_TYPE        VARCHAR2(32),
    BIZ_ID          VARCHAR2(64),
    IDEMPOTENT_KEY  VARCHAR2(64),
    CREATE_BY       VARCHAR2(64)   DEFAULT '',
    CREATE_TIME     TIMESTAMP(0),
    UPDATE_BY       VARCHAR2(64)   DEFAULT '',
    UPDATE_TIME     TIMESTAMP(0),
    REMARK          VARCHAR2(255)  DEFAULT NULL,
    VERSION         NUMBER(10)     DEFAULT 0,
    CONSTRAINT PK_MSG_MAIL_LOG PRIMARY KEY (ID),
    CONSTRAINT UK_MSG_MAIL_LOG_IDEM UNIQUE (BIZ_TYPE, BIZ_ID, TEMPLATE_CODE, IDEMPOTENT_KEY)
