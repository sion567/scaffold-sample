-- 8）站内信消息记录表
CREATE TABLE MESSAGE_DB.msg_inner_message (
    ID              NUMBER(20)     NOT NULL,
    TEMPLATE_ID     NUMBER(20),
    TEMPLATE_CODE   VARCHAR2(64),
    TITLE           VARCHAR2(100)  NOT NULL,
    CONTENT         VARCHAR2(2000) NOT NULL,
    JUMP_URL        VARCHAR2(256),
    RECEIVER_ID     NUMBER(20)     NOT NULL,
    RECEIVER_NAME   VARCHAR2(64),
    READ_FLAG       CHAR(1)        DEFAULT '0',
    READ_TIME       TIMESTAMP(0),
    SENDER_TYPE     CHAR(1)        DEFAULT '0',
    SENDER_ID       NUMBER(20),
    SENDER_NAME     VARCHAR2(64),
    BIZ_TYPE        VARCHAR2(32),
    BIZ_ID          VARCHAR2(64),
    IDEMPOTENT_KEY  VARCHAR2(64),
    CREATE_BY       VARCHAR2(64)   DEFAULT '',
    CREATE_TIME     TIMESTAMP(0),
    UPDATE_BY       VARCHAR2(64)   DEFAULT '',
    UPDATE_TIME     TIMESTAMP(0),
    REMARK          VARCHAR2(255)  DEFAULT NULL,
    VERSION         NUMBER(10)     DEFAULT 0,
    CONSTRAINT PK_MSG_INNER_MESSAGE PRIMARY KEY (ID),
    CONSTRAINT UK_MSG_INNER_MSG_IDEM UNIQUE (BIZ_TYPE, BIZ_ID, TEMPLATE_CODE, RECEIVER_ID, IDEMPOTENT_KEY)
);
COMMENT ON TABLE MESSAGE_DB.msg_inner_message IS '站内信消息记录（按接收人一行一条，含已读状态）';
COMMENT ON COLUMN MESSAGE_DB.msg_inner_message.RECEIVER_NAME IS '冗余姓名（列表免关联）';
COMMENT ON COLUMN MESSAGE_DB.msg_inner_message.READ_FLAG IS '0未读 1已读（字典message_read_flag）';
COMMENT ON COLUMN MESSAGE_DB.msg_inner_message.SENDER_TYPE IS '0系统自动 1人工';
CREATE INDEX MESSAGE_DB.IDX_MSG_INNER_MSG_UNREAD ON MESSAGE_DB.msg_inner_message (RECEIVER_ID, READ_FLAG);
CREATE INDEX MESSAGE_DB.IDX_MSG_INNER_MSG_RECENT ON MESSAGE_DB.msg_inner_message (RECEIVER_ID, CREATE_TIME);
